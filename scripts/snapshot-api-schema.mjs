// Writes a structural snapshot of the Supabase "public" schema into supabase/schema/.
//
// Source: the PostgREST OpenAPI document, read with the service key from .env.local. It carries every
// table and view with column types, nullability, defaults, primary and foreign keys, and the callable
// functions. It does NOT carry indexes, RLS policies, triggers, function bodies, grants or enum
// definitions; for those run `npm run schema:dump` (needs SUPABASE_DB_URL).
//
//   node scripts/snapshot-api-schema.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

function loadEnv(path) {
  const env = {}
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const i = line.indexOf('=')
    if (i > 0 && !line.startsWith('#')) env[line.slice(0, i)] = line.slice(i + 1)
  }
  return env
}

const env = loadEnv('.env.local')
const url = env.NEXT_PUBLIC_SUPABASE_URL
const key = env.SUPABASE_SERVICE_ROLE_KEY
if (!url || !key) throw new Error('NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required in .env.local')

const res = await fetch(`${url}/rest/v1/`, { headers: { apikey: key } })
if (!res.ok) throw new Error(`OpenAPI request failed: ${res.status}`)
const spec = await res.json()

const q = (name) => `"${name}"`

// The API does not say whether a relation is a table or a view. These are the views (and the
// materialized views) identified by the 2026-10-09 security audit; anything else is treated as a table.
const KNOWN_VIEWS = new Set([
  'bio_operations_summary', 'corpus_session_summary', 'live_gateway_health', 'molecular_node_map',
  'p2p_connection_matrix', 'sensor_latest', 'twin_anchor_chain', 'twin_chemo_state',
  'twin_convergence_state', 'twin_stress_status', 'twin_tokenizer_state', 'twin_uwb_state',
  'spectrum_overview', 'twin_opsec_risk', 'node_hardware_timeline',
])

// OpenAPI gives a default as a bare value. Keep expressions (now(), gen_random_uuid(), casts),
// numbers and booleans as they are; quote everything else as a text literal.
function sqlDefault(value) {
  if (typeof value !== 'string') return JSON.stringify(value)
  if (value === '') return "''"
  if (/\(|::/.test(value) || /^(true|false|null)$/i.test(value) || /^-?\d+(\.\d+)?$/.test(value)) return value
  return `'${value.replace(/'/g, "''")}'`
}

const enums = new Map() // enum type name -> values

function pgType(col) {
  if (col.type === 'array') return `${col.items?.format ?? col.items?.type ?? 'text'}[]`
  if (col.format === 'character varying' && col.maxLength) return `character varying(${col.maxLength})`
  if (col.format === 'bit' || col.format === 'bit varying') return col.format
  return col.format ?? col.type ?? 'text'
}

const tables = []
const views = []
for (const [name, def] of Object.entries(spec.definitions ?? {}).sort(([a], [b]) => a.localeCompare(b))) {
  const required = new Set(def.required ?? [])
  const pk = []
  const fks = []
  const cols = Object.entries(def.properties ?? {}).map(([col, c]) => {
    const note = c.description ?? ''
    if (note.includes('<pk/>')) pk.push(col)
    const fk = note.match(/<fk table='([^']+)' column='([^']+)'\/>/)
    if (fk) fks.push({ col, table: fk[1], ref: fk[2] })
    if (c.enum && c.format) enums.set(c.format, c.enum)
    const enumVals = ''
    let line = `  ${q(col)} ${pgType(c)}`
    if (required.has(col)) line += ' not null'
    if (c.default !== undefined && c.default !== null) line += ` default ${sqlDefault(c.default)}`
    return { line, enumVals }
  })
  const isTable = !KNOWN_VIEWS.has(name)
  const body = cols.map((c, i) => c.line + (i < cols.length - 1 || pk.length || fks.length ? ',' : '') + c.enumVals)
  if (pk.length) body.push(`  primary key (${pk.map(q).join(', ')})${fks.length ? ',' : ''}`)
  fks.forEach((f, i) => body.push(`  foreign key (${q(f.col)}) references ${q(f.table)} (${q(f.ref)})${i < fks.length - 1 ? ',' : ''}`))
  const entry = { name, sql: `create table ${q(name)} (\n${body.join('\n')}\n);` }
  ;(isTable ? tables : views).push(entry)
}

const fns = Object.entries(spec.paths ?? {})
  .filter(([p]) => p.startsWith('/rpc/'))
  .map(([p, item]) => {
    const post = item.post ?? {}
    const body = post.parameters?.find((x) => x.in === 'body')?.schema
    return { name: p.slice(5), args: Object.fromEntries(Object.entries(body?.properties ?? {}).map(([k, v]) => [k, v.format ?? v.type])), required: body?.required ?? [] }
  })
  .sort((a, b) => a.name.localeCompare(b.name))

const header = `-- Structural snapshot of the Supabase "public" schema, rebuilt from the PostgREST OpenAPI document.
-- Generated by scripts/snapshot-api-schema.mjs on ${new Date().toISOString().slice(0, 10)}. Project: ${new URL(url).hostname.split('.')[0]}.
--
-- WHAT THIS IS: column names, types, not-null, defaults, primary keys and foreign keys for every table.
-- WHAT THIS IS NOT: indexes, RLS policies, triggers, function bodies, grants, enum definitions or data.
-- Treat it as a map for rebuilding table structure, not a runnable migration. For the complete schema
-- run \`npm run schema:dump\` (needs SUPABASE_DB_URL in .env.local).
`

mkdirSync('supabase/schema', { recursive: true })
const enumSql = [...enums.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, vals]) => `create type ${q(name.replace(/^public\./, ''))} as enum (${vals.map((v) => `'${String(v).replace(/'/g, "''")}'`).join(', ')});`)
  .join('\n')

writeFileSync(
  'supabase/schema/public_tables.snapshot.sql',
  `${header}\n-- ${enums.size} enum types\n\n${enumSql}\n\n-- ${tables.length} tables\n\n${tables.map((t) => t.sql).join('\n\n')}\n`
)
writeFileSync(
  'supabase/schema/public_views.snapshot.sql',
  `${header}\n-- ${views.length} views and materialized views. Column lists only: the API does not expose their SQL\n-- definitions, and the primary/foreign keys shown are inherited from the underlying tables.\n\n${views.map((v) => v.sql.replace('create table', 'create view (columns only)')).join('\n\n')}\n`
)
writeFileSync('supabase/schema/public_functions.snapshot.json', JSON.stringify({ generated: new Date().toISOString().slice(0, 10), functions: fns }, null, 2) + '\n')

console.log(`tables: ${tables.length} | views: ${views.length} | enums: ${enums.size} | functions: ${fns.length}`)
