// Writes the COMPLETE Supabase "public" schema (plus storage policies) to supabase/schema/full_schema.sql:
// extensions, enum types, tables, constraints, indexes, row-level-security state and policies, views,
// functions (full bodies), triggers, and what the anon role may do. Read-only: it never changes the database.
//
//   1. Put SUPABASE_DB_URL in .env.local (Supabase dashboard > Connect > Session pooler URI, with your
//      database password filled in). The file is gitignored; the URL is never printed or written out.
//   2. npm run schema:dump
//
// The output is a readable backup and a map for rebuilding. Statements are grouped by kind, not
// dependency-ordered, so review before running it against an empty database.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import pg from 'pg'

function loadEnv(path) {
  const env = {}
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const i = line.indexOf('=')
    if (i > 0 && !line.startsWith('#')) env[line.slice(0, i)] = line.slice(i + 1).trim().replace(/^["']|["']$/g, '')
  }
  return env
}

const url = loadEnv('.env.local').SUPABASE_DB_URL
if (!url) {
  console.error('SUPABASE_DB_URL is missing from .env.local (see the comment at the top of this script).')
  process.exit(1)
}

const client = new pg.Client({ connectionString: url, ssl: { rejectUnauthorized: false } })
await client.connect()
await client.query('begin read only')

const q = async (text, params) => (await client.query(text, params)).rows
const ident = (s) => `"${String(s).replace(/"/g, '""')}"`
const out = []
const section = (title) => out.push('', `-- ${'='.repeat(70)}`, `-- ${title}`, `-- ${'='.repeat(70)}`, '')

const meta = (await q(`select current_database() as db, version() as v`))[0]
out.push(
  '-- Complete schema dump of the Supabase project (read-only introspection).',
  `-- Generated by scripts/dump-schema.mjs on ${new Date().toISOString().slice(0, 10)}. ${meta.v.split(',')[0]}.`,
  '-- Grouped by kind, not dependency-ordered. Contains no row data and no secrets.'
)

// ---- extensions
section('Extensions')
for (const r of await q(`select extname, extversion, n.nspname from pg_extension e join pg_namespace n on n.oid = e.extnamespace order by 1`))
  out.push(`create extension if not exists ${ident(r.extname)} with schema ${ident(r.nspname)};  -- ${r.extversion}`)

// ---- enum types
section('Enum types (public)')
for (const r of await q(`
  select t.typname, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by 1`))
  out.push(`create type public.${ident(r.typname)} as enum (${r.labels.map((l) => `'${l.replace(/'/g, "''")}'`).join(', ')});`)

// ---- tables
section('Tables (public)')
const rels = await q(`
  select c.oid, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity, c.reloptions
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p','v','m') order by c.relname`)
const tables = rels.filter((r) => r.relkind === 'r' || r.relkind === 'p')
for (const t of tables) {
  const cols = await q(`
    select a.attname, format_type(a.atttypid, a.atttypmod) as type, a.attnotnull, a.attidentity, a.attgenerated,
           pg_get_expr(d.adbin, d.adrelid) as def
    from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = $1 and a.attnum > 0 and not a.attisdropped order by a.attnum`, [t.oid])
  const cons = await q(`select conname, pg_get_constraintdef(oid) as def from pg_constraint where conrelid = $1 order by contype, conname`, [t.oid])
  const lines = cols.map((c) => {
    let s = `  ${ident(c.attname)} ${c.type}`
    if (c.attidentity === 'a') s += ' generated always as identity'
    else if (c.attidentity === 'd') s += ' generated by default as identity'
    else if (c.attgenerated === 's') s += ` generated always as (${c.def}) stored`
    else if (c.def !== null) s += ` default ${c.def}`
    if (c.attnotnull) s += ' not null'
    return s
  })
  for (const c of cons) lines.push(`  constraint ${ident(c.conname)} ${c.def}`)
  out.push(`create table public.${ident(t.relname)} (`, lines.join(',\n'), ');', '')
}

// ---- indexes not already created by a constraint
section('Indexes (those not created by a primary key or unique constraint)')
for (const r of await q(`
  select pg_get_indexdef(i.indexrelid) as def from pg_index i
  join pg_class c on c.oid = i.indrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)
  order by 1`))
  out.push(`${r.def};`)

// ---- row level security + policies
section('Row level security')
for (const t of tables) {
  if (t.relrowsecurity) out.push(`alter table public.${ident(t.relname)} enable row level security;`)
  if (t.relforcerowsecurity) out.push(`alter table public.${ident(t.relname)} force row level security;`)
}
const off = tables.filter((t) => !t.relrowsecurity).map((t) => t.relname)
out.push('', `-- tables WITHOUT row level security (${off.length}): ${off.join(', ') || 'none'}`)

section('Policies (public and storage)')
for (const r of await q(`
  select schemaname, tablename, policyname, permissive, roles::text[] as roles, cmd, qual, with_check from pg_policies
  where schemaname in ('public','storage') order by schemaname, tablename, policyname`)) {
  out.push(
    `create policy ${ident(r.policyname)} on ${r.schemaname}.${ident(r.tablename)} as ${r.permissive.toLowerCase()} for ${r.cmd.toLowerCase()} to ${r.roles.join(', ')}` +
      (r.qual ? ` using (${r.qual})` : '') + (r.with_check ? ` with check (${r.with_check})` : '') + ';'
  )
}

// ---- views
section('Views and materialized views (public)')
for (const v of rels.filter((r) => r.relkind === 'v' || r.relkind === 'm')) {
  const def = (await q(`select pg_get_viewdef($1::oid, true) as d`, [v.oid]))[0].d
  const opts = v.reloptions?.length ? ` with (${v.reloptions.join(', ')})` : ''
  out.push(`create ${v.relkind === 'm' ? 'materialized view' : 'view'} public.${ident(v.relname)}${opts} as`, def.replace(/;?\s*$/, ';'), '')
}

// ---- functions
section('Functions (public, excluding extension-owned)')
for (const f of await q(`
  select p.oid, p.proname, pg_get_functiondef(p.oid) as def, p.prosecdef
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  order by p.proname, p.oid`))
  out.push(`${f.def.replace(/;?\s*$/, ';')}`, '')

// ---- triggers
section('Triggers (public)')
for (const r of await q(`
  select pg_get_triggerdef(t.oid) as def from pg_trigger t join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and not t.tgisinternal order by 1`))
  out.push(`${r.def};`)
for (const r of await q(`select evtname, evtevent, evtfoid::regproc::text as fn, evtenabled from pg_event_trigger order by 1`))
  out.push(`-- event trigger ${r.evtname}: on ${r.evtevent} executes ${r.fn} (enabled: ${r.evtenabled})`)

// ---- what the logged-out (anon) role can do
section('Access for the anon role (the public key) - review this')
const anonTables = await q(`
  select c.relname, array_remove(array[
      case when has_table_privilege('anon', c.oid, 'select') then 'select' end,
      case when has_table_privilege('anon', c.oid, 'insert') then 'insert' end,
      case when has_table_privilege('anon', c.oid, 'update') then 'update' end,
      case when has_table_privilege('anon', c.oid, 'delete') then 'delete' end], null) as privs
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p','v','m') order by 1`)
const writers = anonTables.filter((r) => r.privs.some((p) => p !== 'select'))
out.push(`-- anon can WRITE to ${writers.length} relations: ${writers.map((r) => `${r.relname} (${r.privs.join('/')})`).join(', ') || 'none'}`)
const fnAnon = await q(`
  select p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as sig, p.prosecdef
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p') and has_function_privilege('anon', p.oid, 'execute') order by 1`)
out.push(`-- anon can EXECUTE ${fnAnon.length} functions; of those, security definer: ${fnAnon.filter((f) => f.prosecdef).map((f) => f.sig).join(', ') || 'none'}`)

await client.query('rollback')
await client.end()

mkdirSync('supabase/schema', { recursive: true })
writeFileSync('supabase/schema/full_schema.sql', out.join('\n') + '\n')
console.log(`wrote supabase/schema/full_schema.sql (${out.length} lines): ${tables.length} tables, ${rels.length - tables.length} views, ${off.length} without RLS`)
